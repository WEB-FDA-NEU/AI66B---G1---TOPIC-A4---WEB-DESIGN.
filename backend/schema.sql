BEGIN;

-- User roles are strings with checks so role changes do not require enum migrations.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(20),
    role VARCHAR(20) NOT NULL DEFAULT 'customer',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_role CHECK (role IN ('customer', 'staff', 'admin'))
);

COMMENT ON TABLE users IS 'User accounts; password_hash stores a bcrypt/Argon2 hash, never plaintext.';
COMMENT ON CONSTRAINT ck_users_role ON users IS 'Restricts account roles to supported values.';
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users (lower(email));

-- Concert schedule and sale windows; nullable sale bounds allow an unset schedule.
CREATE TABLE IF NOT EXISTS concerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    artist VARCHAR(255) NOT NULL,
    description TEXT,
    venue VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    poster_url TEXT,
    starts_at TIMESTAMPTZ NOT NULL,
    doors_open_at TIMESTAMPTZ,
    sale_start_at TIMESTAMPTZ,
    sale_end_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_concerts_status CHECK (status IN ('draft', 'on_sale', 'sold_out', 'cancelled', 'completed')),
    CONSTRAINT ck_concerts_sale_window CHECK (sale_end_at IS NULL OR sale_start_at IS NULL OR sale_end_at > sale_start_at),
    CONSTRAINT ck_concerts_doors_before_start CHECK (doors_open_at IS NULL OR doors_open_at <= starts_at)
);

COMMENT ON TABLE concerts IS 'Concert listings, venues, schedules, and sale windows.';
COMMENT ON CONSTRAINT ck_concerts_status ON concerts IS 'Restricts concert lifecycle states.';
COMMENT ON CONSTRAINT ck_concerts_sale_window ON concerts IS 'Requires the sale end to follow its start when both are set.';
COMMENT ON CONSTRAINT ck_concerts_doors_before_start ON concerts IS 'Doors cannot open after the concert starts.';
CREATE INDEX IF NOT EXISTS ix_concerts_status_starts_at ON concerts (status, starts_at);

-- A concert's ticket tiers define the price and capacity for their seats.
CREATE TABLE IF NOT EXISTS zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL REFERENCES concerts(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    price NUMERIC(12, 0) NOT NULL,
    capacity INTEGER NOT NULL,
    color VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_zones_price_nonnegative CHECK (price >= 0),
    CONSTRAINT ck_zones_capacity_positive CHECK (capacity > 0),
    CONSTRAINT uq_zones_concert_name UNIQUE (concert_id, name)
);

COMMENT ON TABLE zones IS 'Ticket tiers (for example VIP or CAT1) belonging to a concert.';
COMMENT ON CONSTRAINT ck_zones_price_nonnegative ON zones IS 'Ticket tier prices cannot be negative.';
COMMENT ON CONSTRAINT ck_zones_capacity_positive ON zones IS 'A ticket tier must have positive capacity.';
COMMENT ON CONSTRAINT uq_zones_concert_name ON zones IS 'Tier names are unique within each concert.';
CREATE INDEX IF NOT EXISTS ix_zones_concert_id ON zones (concert_id);

-- Reservations temporarily associate a user with seats until expires_at.
CREATE TABLE IF NOT EXISTS reservations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL REFERENCES users(id),
    concert_id BIGINT NOT NULL REFERENCES concerts(id),
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_reservations_status CHECK (status IN ('active', 'converted', 'expired', 'cancelled')),
    CONSTRAINT ck_reservations_expires_after_created CHECK (expires_at > created_at)
);

COMMENT ON TABLE reservations IS 'Temporary seat-hold sessions for a user and concert.';
COMMENT ON CONSTRAINT ck_reservations_status ON reservations IS 'Restricts reservation lifecycle states.';
COMMENT ON CONSTRAINT ck_reservations_expires_after_created ON reservations IS 'A reservation must expire after it is created.';
CREATE INDEX IF NOT EXISTS ix_reservations_user_status ON reservations (user_id, status);
CREATE INDEX IF NOT EXISTS ix_reservations_active_expires_at ON reservations (expires_at) WHERE status = 'active';

-- Seats inherit their tier price; active holds must identify both expiry and reservation.
CREATE TABLE IF NOT EXISTS seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL REFERENCES zones(id) ON DELETE CASCADE,
    row_label VARCHAR(10) NOT NULL,
    seat_number INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'available',
    held_until TIMESTAMPTZ,
    reservation_id UUID REFERENCES reservations(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_seats_number_positive CHECK (seat_number > 0),
    CONSTRAINT ck_seats_status CHECK (status IN ('available', 'held', 'sold')),
    CONSTRAINT ck_seats_hold_fields CHECK (
        (status <> 'held' OR (held_until IS NOT NULL AND reservation_id IS NOT NULL))
        AND (status NOT IN ('available', 'sold') OR held_until IS NULL)
    ),
    CONSTRAINT uq_seats_zone_row_number UNIQUE (zone_id, row_label, seat_number)
);

COMMENT ON TABLE seats IS 'Numbered seats belonging to a ticket tier.';
COMMENT ON CONSTRAINT ck_seats_number_positive ON seats IS 'Seat numbers must be positive.';
COMMENT ON CONSTRAINT ck_seats_status ON seats IS 'Restricts seat states to available, held, or sold.';
COMMENT ON CONSTRAINT ck_seats_hold_fields ON seats IS 'Held seats need an expiry and reservation; other states cannot retain a hold expiry.';
COMMENT ON CONSTRAINT uq_seats_zone_row_number ON seats IS 'Seat labels are unique within a ticket tier.';
CREATE INDEX IF NOT EXISTS ix_seats_zone_status ON seats (zone_id, status);
CREATE INDEX IF NOT EXISTS ix_seats_held_until ON seats (held_until) WHERE status = 'held';
CREATE INDEX IF NOT EXISTS ix_seats_reservation_id ON seats (reservation_id);

-- Order numbers are human-facing and deliberately start at 10483.
CREATE SEQUENCE IF NOT EXISTS order_number_seq START WITH 10483 INCREMENT BY 1;

-- Orders retain payment and refund state alongside the purchased total.
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number BIGINT NOT NULL DEFAULT nextval('order_number_seq'),
    user_id BIGINT NOT NULL REFERENCES users(id),
    concert_id BIGINT NOT NULL REFERENCES concerts(id),
    reservation_id UUID UNIQUE REFERENCES reservations(id),
    total_amount NUMERIC(12, 0) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    payment_method VARCHAR(30),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid',
    payment_ref VARCHAR(100),
    paid_at TIMESTAMPTZ,
    refund_status VARCHAR(20) NOT NULL DEFAULT 'none',
    refund_amount NUMERIC(12, 0) NOT NULL DEFAULT 0,
    refund_reason TEXT,
    refunded_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_orders_order_number UNIQUE (order_number),
    CONSTRAINT ck_orders_total_nonnegative CHECK (total_amount >= 0),
    CONSTRAINT ck_orders_status CHECK (status IN ('pending', 'paid', 'cancelled', 'failed')),
    CONSTRAINT ck_orders_payment_status CHECK (payment_status IN ('unpaid', 'paid', 'failed', 'refunded')),
    CONSTRAINT ck_orders_refund_status CHECK (refund_status IN ('none', 'requested', 'refunded', 'rejected')),
    CONSTRAINT ck_orders_refund_amount CHECK (refund_amount >= 0 AND refund_amount <= total_amount),
    CONSTRAINT ck_orders_paid_at CHECK (payment_status NOT IN ('paid', 'refunded') OR paid_at IS NOT NULL),
    CONSTRAINT ck_orders_refunded_at CHECK (refund_status <> 'refunded' OR refunded_at IS NOT NULL)
);

ALTER SEQUENCE order_number_seq OWNED BY orders.order_number;

COMMENT ON TABLE orders IS 'A purchase, payment, and refund record for a user.';
COMMENT ON CONSTRAINT uq_orders_order_number ON orders IS 'Provides a unique human-facing order number.';
COMMENT ON CONSTRAINT ck_orders_total_nonnegative ON orders IS 'Order totals cannot be negative.';
COMMENT ON CONSTRAINT ck_orders_status ON orders IS 'Restricts order lifecycle states.';
COMMENT ON CONSTRAINT ck_orders_payment_status ON orders IS 'Restricts payment states.';
COMMENT ON CONSTRAINT ck_orders_refund_status ON orders IS 'Restricts refund workflow states.';
COMMENT ON CONSTRAINT ck_orders_refund_amount ON orders IS 'Refunds must be nonnegative and cannot exceed the order total.';
COMMENT ON CONSTRAINT ck_orders_paid_at ON orders IS 'Paid or refunded payments require a payment timestamp.';
COMMENT ON CONSTRAINT ck_orders_refunded_at ON orders IS 'Completed refunds require a refund timestamp.';
CREATE INDEX IF NOT EXISTS ix_orders_user_created_at ON orders (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_orders_concert_id ON orders (concert_id);
CREATE INDEX IF NOT EXISTS ix_orders_status ON orders (status);

-- Tickets are issued per seat; only valid/used tickets reserve a seat uniquely.
CREATE TABLE IF NOT EXISTS tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    concert_id BIGINT NOT NULL REFERENCES concerts(id),
    seat_id BIGINT NOT NULL REFERENCES seats(id),
    ticket_code VARCHAR(64) NOT NULL,
    price NUMERIC(12, 0) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'valid',
    checked_in_at TIMESTAMPTZ,
    checked_in_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_tickets_ticket_code UNIQUE (ticket_code),
    CONSTRAINT ck_tickets_price_nonnegative CHECK (price >= 0),
    CONSTRAINT ck_tickets_status CHECK (status IN ('valid', 'used', 'cancelled', 'refunded')),
    CONSTRAINT ck_tickets_checkin_status CHECK ((status = 'used') = (checked_in_at IS NOT NULL))
);

COMMENT ON TABLE tickets IS 'Issued concert tickets and check-in details.';
COMMENT ON CONSTRAINT uq_tickets_ticket_code ON tickets IS 'Ticket codes (including QR payloads) are unique.';
COMMENT ON CONSTRAINT ck_tickets_price_nonnegative ON tickets IS 'Recorded ticket prices cannot be negative.';
COMMENT ON CONSTRAINT ck_tickets_status ON tickets IS 'Restricts ticket lifecycle states.';
COMMENT ON CONSTRAINT ck_tickets_checkin_status ON tickets IS 'A ticket is used exactly when it has a check-in timestamp.';
CREATE UNIQUE INDEX IF NOT EXISTS uq_tickets_seat_active ON tickets (seat_id) WHERE status IN ('valid', 'used');
CREATE INDEX IF NOT EXISTS ix_tickets_order_id ON tickets (order_id);
CREATE INDEX IF NOT EXISTS ix_tickets_concert_id ON tickets (concert_id);

COMMIT;
